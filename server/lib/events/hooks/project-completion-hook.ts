/**
 * Project Completion Hook
 *
 * When all tasks in a project reach terminal states, creates a final PR
 * from the project branch → main (or the project's configured base branch).
 *
 * Only fires for projects that have a GitHub repo configured and a project branch.
 */

import type { AstroEvent, EventHook } from '../types.js'
import { db } from '../../db/index.js'
import { projects, planNodes } from '../../db/schema.js'
import { eq } from 'drizzle-orm'
import type { Project, PlanNode } from '../../../../src/types/index.js'

const TERMINAL_STATUSES = new Set(['completed', 'auto_verified', 'pruned'])

/**
 * Check if all task/milestone nodes in a project are in terminal states.
 */
async function allNodesComplete(projectId: string): Promise<{ complete: boolean; nodes: PlanNode[] }> {
  const rows = await db.select().from(planNodes)
    .where(eq(planNodes.projectId, projectId))

  // Filter to non-deleted nodes
  const activeNodes = rows.filter(n => !n.deletedAt) as unknown as PlanNode[]

  if (activeNodes.length === 0) {
    return { complete: false, nodes: [] }
  }

  const allDone = activeNodes.every(n => TERMINAL_STATUSES.has(n.status))
  return { complete: allDone, nodes: activeNodes }
}

/**
 * Build a detailed, informative PR body summarizing all task work in the project.
 *
 * Template includes: project overview, per-task details with execution summaries,
 * files changed, key findings, and follow-up items.
 */
function buildProjectPrBody(project: Project, nodes: PlanNode[]): string {
  const parts: string[] = []

  // ── Header ──────────────────────────────────────────────────────────
  parts.push(`## ${project.name}`)
  parts.push('')
  if (project.description) {
    parts.push(`> ${project.description}`)
    parts.push('')
  }

  // ── Stats ───────────────────────────────────────────────────────────
  const taskNodes = nodes
    .filter(n => n.type === 'task')
    .sort((a, b) => (a.number ?? 0) - (b.number ?? 0))
  const completedCount = taskNodes.filter(n => n.status === 'completed' || n.status === 'auto_verified').length
  const prunedCount = taskNodes.filter(n => n.status === 'pruned').length

  parts.push(`**${completedCount}** tasks completed${prunedCount > 0 ? ` · **${prunedCount}** pruned` : ''}`)
  parts.push('')

  // ── Task Details ────────────────────────────────────────────────────
  parts.push('### Tasks')
  parts.push('')

  for (const node of taskNodes) {
    if (node.status === 'pruned') {
      parts.push(`<details><summary>~~${node.title}~~ (pruned)</summary></details>`)
      parts.push('')
      continue
    }

    // Parse execution output for structured summary if available
    const summary = parseSummaryFromOutput(node.executionOutput)
    const prLink = node.prUrl ? ` — [PR](${node.prUrl})` : ''

    parts.push(`<details>`)
    parts.push(`<summary><strong>${node.title}</strong>${prLink}</summary>`)
    parts.push('')

    if (summary.workCompleted) {
      parts.push(summary.workCompleted)
      parts.push('')
    } else if (node.executionOutput) {
      // Fallback: truncated raw output
      const truncated = node.executionOutput.length > 500
        ? node.executionOutput.slice(0, 500) + '...'
        : node.executionOutput
      parts.push(truncated)
      parts.push('')
    }

    if (summary.keyFindings && summary.keyFindings.length > 0) {
      parts.push('**Key findings:**')
      for (const finding of summary.keyFindings) {
        parts.push(`- ${finding}`)
      }
      parts.push('')
    }

    if (summary.filesChanged && summary.filesChanged.length > 0) {
      parts.push('**Files changed:**')
      for (const file of summary.filesChanged.slice(0, 20)) {
        parts.push(`- \`${file}\``)
      }
      if (summary.filesChanged.length > 20) {
        parts.push(`- ... and ${summary.filesChanged.length - 20} more`)
      }
      parts.push('')
    }

    parts.push(`</details>`)
    parts.push('')
  }

  // ── Aggregate Follow-ups ────────────────────────────────────────────
  const allFollowUps = taskNodes.flatMap(n => {
    const s = parseSummaryFromOutput(n.executionOutput)
    return (s.followUps ?? []).map(f => ({ task: n.title, followUp: f }))
  })
  if (allFollowUps.length > 0) {
    parts.push('### Follow-up Items')
    parts.push('')
    for (const { task, followUp } of allFollowUps) {
      parts.push(`- [ ] ${followUp} _(from: ${task})_`)
    }
    parts.push('')
  }

  // ── Footer ──────────────────────────────────────────────────────────
  parts.push('---')
  parts.push('*Generated by [Astro](https://astroanywhere.com) — AI-assisted project planning and execution*')

  return parts.join('\n')
}

/**
 * Try to extract structured summary fields from execution output.
 * The agent-runner stores a JSON summary in the executionOutput field when available.
 */
function parseSummaryFromOutput(output?: string | null): {
  workCompleted?: string
  keyFindings?: string[]
  filesChanged?: string[]
  followUps?: string[]
} {
  if (!output) return {}

  // Try to parse JSON summary embedded in output (agent-runner format)
  try {
    const parsed = JSON.parse(output)
    if (parsed && typeof parsed === 'object') {
      return {
        workCompleted: parsed.workCompleted ?? parsed.executiveSummary,
        keyFindings: parsed.keyFindings,
        filesChanged: parsed.filesChanged,
        followUps: parsed.followUps,
      }
    }
  } catch {
    // Not JSON — that's fine, use raw text
  }

  return {}
}

/**
 * Create the final project PR from project branch → base branch.
 */
async function createProjectPr(
  project: Project,
  projectBranch: string,
  baseBranch: string,
  nodes: PlanNode[],
): Promise<{ prUrl?: string; prNumber?: number }> {
  const ghRepo = project.githubOwner && project.githubRepo
    ? `${project.githubOwner}/${project.githubRepo}`
    : null

  if (!ghRepo) {
    console.log('[project-completion-hook] No GitHub repo configured, skipping final PR')
    return {}
  }

  // Use GitHub API to create the PR (server-side, no gh CLI dependency)
  // We need a GitHub token — fetch from the project owner's GitHub connection
  const { githubStore } = await import('../../github-store.js')

  // Get ownerId from the DB project record (not exposed in the Project interface)
  const [dbProject] = await db.select({ ownerId: projects.ownerId })
    .from(projects).where(eq(projects.id, project.id)).limit(1)
  if (!dbProject) {
    console.warn('[project-completion-hook] Project not found in DB')
    return {}
  }

  const ghConnection = await githubStore.getConnection(dbProject.ownerId)
  if (!ghConnection?.accessToken) {
    console.warn('[project-completion-hook] No GitHub token available for final PR')
    return {}
  }
  const ghToken = ghConnection.accessToken

  const body = buildProjectPrBody(project, nodes)

  try {
    const response = await fetch(
      `https://api.github.com/repos/${ghRepo}/pulls`,
      {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${ghToken}`,
          Accept: 'application/vnd.github.v3+json',
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          title: `[Astro] ${project.name}`,
          body,
          head: projectBranch,
          base: baseBranch,
        }),
      },
    )

    if (response.ok) {
      const data = await response.json() as { html_url: string; number: number }
      console.log(`[project-completion-hook] Created final PR #${data.number}: ${data.html_url}`)
      return { prUrl: data.html_url, prNumber: data.number }
    } else {
      const errText = await response.text()
      console.warn(`[project-completion-hook] Failed to create final PR: ${response.status} ${errText}`)
      return {}
    }
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err)
    console.error(`[project-completion-hook] Error creating final PR: ${msg}`)
    return {}
  }
}

export const projectCompletionHook: EventHook = async (event: AstroEvent) => {
  if (event.type !== 'task.completed') return
  if (event.result.status !== 'success') return

  const { projectId, project } = event
  if (!project) return

  // Only process projects with a GitHub repo
  if (!project.githubOwner || !project.githubRepo) return

  // Check if all nodes are complete
  const { complete, nodes } = await allNodesComplete(projectId)
  if (!complete) return

  // Skip if project has an explicit "Push to GitHub" task node — that node handles PR creation
  const pushToGithubNode = nodes.find(n =>
    n.type === 'task' && !n.deletedAt && n.status !== 'pruned' &&
    /push\s+to\s+github|publish\s+to\s+github/i.test(n.title)
  )
  if (pushToGithubNode) {
    console.log(`[project-completion-hook] Skipping — project has explicit Push to GitHub node (${pushToGithubNode.id})`)
    return
  }

  // Skip if we already created a project PR
  if (project.projectPrUrl) {
    console.log(`[project-completion-hook] Project ${projectId} already has a PR: ${project.projectPrUrl}`)
    return
  }

  // Determine the project branch
  const projectBranch = project.projectBranch
  if (!projectBranch) {
    console.log(`[project-completion-hook] Project ${projectId} has no project branch, skipping`)
    return
  }

  // Determine the base branch (where the final PR targets)
  const baseBranch = (project.source as { baseBranch?: string } | undefined)?.baseBranch ?? 'main'

  console.log(`[project-completion-hook] All tasks complete for project ${projectId}, creating final PR: ${projectBranch} → ${baseBranch}`)

  const { prUrl, prNumber } = await createProjectPr(project, projectBranch, baseBranch, nodes)

  if (prUrl) {
    // Persist to project record
    try {
      await db.update(projects)
        .set({
          projectBranch,
          projectPrUrl: prUrl,
          projectPrNumber: prNumber,
          updatedAt: new Date(),
        })
        .where(eq(projects.id, projectId))
      console.log(`[project-completion-hook] Persisted final PR data to project ${projectId}`)
    } catch (dbErr) {
      const msg = dbErr instanceof Error ? dbErr.message : String(dbErr)
      console.error(`[project-completion-hook] Failed to persist PR data: ${msg}`)
    }
  }
}
