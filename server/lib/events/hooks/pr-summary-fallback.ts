/**
 * PR Summary Fallback Chain
 *
 * Extracts and exports the PR body generation fallback chain logic
 * for testability. This module provides a 5-layer fallback chain:
 *
 * 1. Structured summary from agent (result.summary)
 * 2. Executive summary parsed from execution output
 * 3. Server-generated summary via Anthropic API
 * 4. File changes summary from result.filesChanged
 * 5. Task description fallback (node.title + node.description)
 */

import { generateServerSideSummary, type SummaryInput } from '../../../../packages/core/src/dispatch/summary-utils.js'

/** Source of the PR summary content */
export type PrSummarySource =
  | 'structured'       // Layer 1: Agent's structured summary
  | 'parsed'           // Layer 2: Parsed executive summary from output
  | 'server_generated' // Layer 3: Server-generated via Anthropic
  | 'file_changes'     // Layer 4: File changes summary
  | 'task_description' // Layer 5: Task description fallback

/** Result of the PR summary fallback chain */
export interface PrSummaryResult {
  /** The generated PR body content */
  body: string
  /** Which layer produced this content */
  source: PrSummarySource
}

/** Input for the PR summary fallback chain */
export interface PrSummaryInput {
  /** Task result summary from agent */
  summary?: {
    workCompleted?: string
    executiveSummary?: string
    keyFindings?: string[]
    filesChanged?: string[]
    followUps?: string[]
    status?: 'success' | 'partial' | 'failure'
  }
  /** Standard output from task execution */
  stdout?: string
  /** Files changed during execution */
  filesChanged?: Array<{ path: string; diff?: string }>
  /** Task node information */
  node: {
    title: string
    description?: string
    githubIssueUrl?: string
    githubIssueNumber?: number
  }
  /** Astro base URL for links */
  astroBaseUrl?: string
  /** Project ID */
  projectId?: string
  /** Node ID */
  nodeId?: string
}

/** Options for controlling fallback chain behavior */
export interface FallbackChainOptions {
  /** Custom server summary generator (for testing) */
  serverSummaryGenerator?: typeof generateServerSideSummary
  /** Skip server summary generation (for testing without API) */
  skipServerSummary?: boolean
}

// ── Executive Summary Parsing ───────────────────────────────────────────

/**
 * Parse an executive summary from execution output text.
 * Looks for a "## Executive Summary" markdown section.
 *
 * Exported for testing.
 */
export function parseExecutiveSummaryFromOutput(output: string): string | null {
  // Match "## Executive Summary" followed by content until next ## heading or end
  const pattern = /## Executive Summary\s*\n([\s\S]*?)(?=\n## |\n---|$)/i
  const match = output.match(pattern)
  if (!match?.[1]) return null

  const summary = match[1].trim()
  // Must be at least 20 chars to be meaningful
  return summary.length >= 20 ? summary : null
}

// ── PR Body Formatting ──────────────────────────────────────────────────

interface PrBodyInput {
  summary?: string
  changes?: string[]
  filesChanged?: string[]
  testPlan?: string[]
  astroUrl?: string
  relatedIssue?: string
}

/**
 * Format the PR body with structured sections.
 * Exported for testing.
 */
export function formatPrBody(input: PrBodyInput): string {
  const parts: string[] = []

  // ## Summary
  if (input.summary) {
    parts.push(`## Summary\n\n${input.summary}`)
  }

  // ## Changes (key findings / bullet points)
  if (input.changes && input.changes.length > 0) {
    parts.push(`## Changes\n\n${input.changes.map((c) => `- ${c}`).join('\n')}`)
  }

  // ## Files Changed
  if (input.filesChanged && input.filesChanged.length > 0) {
    const fileList = input.filesChanged.slice(0, 30) // Cap at 30 files
    parts.push(`## Files Changed\n\n${fileList.map((f) => `- \`${f}\``).join('\n')}`)
    if (input.filesChanged.length > 30) {
      parts.push(`\n_...and ${input.filesChanged.length - 30} more files_`)
    }
  }

  // ## Test Plan (from follow-ups that look like test actions)
  if (input.testPlan && input.testPlan.length > 0) {
    parts.push(`## Test Plan\n\n${input.testPlan.map((t) => `- [ ] ${t}`).join('\n')}`)
  }

  // ## Astro link
  if (input.astroUrl) {
    parts.push(`## Astro\n\n[View task in Astro](${input.astroUrl})`)
  }

  // ## Related Issue
  if (input.relatedIssue) {
    parts.push(`## Related Issue\n\nCloses ${input.relatedIssue}`)
  }

  // Footer
  parts.push('---\n*PR description generated by [Astro](https://astroanywhere.com)*')

  return parts.join('\n\n')
}

// ── Fallback Chain ──────────────────────────────────────────────────────

/**
 * Run the PR summary fallback chain to generate the best PR body.
 *
 * Uses a 5-layer fallback chain:
 * 1. Structured summary (input.summary)
 * 2. Executive summary parsed from stdout
 * 3. Server-generated summary (Anthropic API)
 * 4. File changes summary
 * 5. Task description
 *
 * @param input - PR summary input containing task result and node info
 * @param options - Optional configuration for testing
 * @returns PR body content with source indicator
 */
export async function runPrSummaryFallbackChain(
  input: PrSummaryInput,
  options: FallbackChainOptions = {},
): Promise<PrSummaryResult | null> {
  const { summary, stdout, filesChanged, node } = input

  // Build Astro link if possible
  const baseUrl = input.astroBaseUrl || process.env.ASTRO_BASE_URL || 'http://localhost:5173'
  const astroUrl = input.projectId && input.nodeId
    ? `${baseUrl}/project/${input.projectId}/task/${input.nodeId}`
    : undefined

  // Build related issue reference
  let relatedIssue: string | undefined
  if (node.githubIssueUrl) {
    relatedIssue = node.githubIssueUrl
  } else if (node.githubIssueNumber) {
    relatedIssue = `#${node.githubIssueNumber}`
  }

  // ── Layer 1: Structured summary from agent ────────────────────────
  if (summary?.workCompleted) {
    // Extract test plan from follow-ups that look like test actions
    const testPlan = summary.followUps?.filter((f) =>
      /test|verify|check|validate|confirm/i.test(f)
    )
    const nonTestFollowUps = summary.followUps?.filter((f) =>
      !/test|verify|check|validate|confirm/i.test(f)
    )

    // Build summary text — prefer executiveSummary, fallback to workCompleted
    const summaryText = summary.executiveSummary || summary.workCompleted

    // Merge keyFindings + non-test follow-ups as changes
    const changes = [
      ...(summary.keyFindings || []),
      ...(nonTestFollowUps && nonTestFollowUps.length > 0
        ? [`**Follow-ups:** ${nonTestFollowUps.join(', ')}`]
        : []),
    ]

    return {
      body: formatPrBody({
        summary: summaryText,
        changes: changes.length > 0 ? changes : undefined,
        filesChanged: summary.filesChanged,
        testPlan: testPlan && testPlan.length > 0 ? testPlan : undefined,
        astroUrl,
        relatedIssue,
      }),
      source: 'structured',
    }
  }

  // ── Layer 2: Parse executive summary from stdout ──────────────────
  if (stdout) {
    const execSummary = parseExecutiveSummaryFromOutput(stdout)
    if (execSummary) {
      const filePathsFromResult = filesChanged?.map((f) => f.path)
      return {
        body: formatPrBody({
          summary: execSummary,
          filesChanged: filePathsFromResult,
          astroUrl,
          relatedIssue,
        }),
        source: 'parsed',
      }
    }
  }

  // ── Layer 3: Server-generated summary via Anthropic API ───────────
  if (!options.skipServerSummary && (stdout || (filesChanged && filesChanged.length > 0))) {
    try {
      const generator = options.serverSummaryGenerator ?? generateServerSideSummary
      const summaryInput: SummaryInput = {
        taskTitle: node.title,
        taskDescription: node.description || '',
        executionOutput: stdout || '',
        fileChanges: (filesChanged || []).map((f) => ({
          path: f.path,
          action: f.diff ? 'modified' : 'changed',
        })),
        status: 'success',
      }

      const serverSummary = await generator(summaryInput)

      if (serverSummary) {
        const summaryText = serverSummary.executiveSummary || serverSummary.workCompleted
        return {
          body: formatPrBody({
            summary: summaryText,
            changes: serverSummary.keyFindings.length > 0 ? serverSummary.keyFindings : undefined,
            filesChanged: serverSummary.filesChanged,
            astroUrl,
            relatedIssue,
          }),
          source: 'server_generated',
        }
      }
    } catch {
      // Server summary generation failed, continue to next layer
    }
  }

  // ── Layer 4: File changes summary ─────────────────────────────────
  if (filesChanged && filesChanged.length > 0) {
    const filePaths = filesChanged.map((f) => f.path)
    return {
      body: formatPrBody({
        summary: `Completed task: ${node.title}`,
        changes: [`Modified ${filePaths.length} file(s)`],
        filesChanged: filePaths,
        astroUrl,
        relatedIssue,
      }),
      source: 'file_changes',
    }
  }

  // ── Layer 5: Task description fallback ────────────────────────────
  const description = node.description || node.title
  if (!description) return null

  return {
    body: formatPrBody({
      summary: description.length > 500 ? description.slice(0, 500) + '…' : description,
      astroUrl,
      relatedIssue,
    }),
    source: 'task_description',
  }
}
