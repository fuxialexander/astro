#!/usr/bin/env bash
set -euo pipefail

# ─────────────────────────────────────────────────────────────────────
# dev-supabase-local.sh
#
# One-line launcher for local Supabase mode development.
# Kills stale processes, ensures Supabase is running, configures
# .env.local for localhost, resets DB if needed, and starts dev server.
#
# Usage:
#   bash scripts/dev-supabase-local.sh          # normal start
#   bash scripts/dev-supabase-local.sh --reset   # reset DB before start
# ─────────────────────────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

RESET_DB=false
if [[ "${1:-}" == "--reset" ]]; then
  RESET_DB=true
fi

echo "╔══════════════════════════════════════════╗"
echo "║  Astro — Local Supabase Dev Launcher     ║"
echo "╚══════════════════════════════════════════╝"
echo ""

# ── 1. Kill stale processes ──────────────────────────────────────────
echo "→ Killing stale processes on ports 5173, 5174, 3001, 3002..."
STALE_PIDS=$(lsof -ti :5173,:5174,:3001,:3002 2>/dev/null || true)
if [[ -n "$STALE_PIDS" ]]; then
  echo "$STALE_PIDS" | xargs kill -9 2>/dev/null || true
  sleep 1
  echo "  ✓ Killed stale processes"
else
  echo "  ✓ No stale processes found"
fi

# ── 2. Check prerequisites ──────────────────────────────────────────
if ! command -v supabase &>/dev/null; then
  echo "✗ Supabase CLI not found. Install with: brew install supabase/tap/supabase"
  exit 1
fi

if ! docker info &>/dev/null; then
  echo "✗ Docker is not running. Start Docker Desktop and try again."
  exit 1
fi
echo "→ Prerequisites: Docker ✓  Supabase CLI ✓"

# ── 3. Start Supabase (if not already running) ──────────────────────
echo ""
echo "→ Checking Supabase status..."
if supabase status &>/dev/null; then
  echo "  ✓ Supabase is already running"
else
  echo "  Starting Supabase (this may take a minute on first run)..."
  supabase start
  echo "  ✓ Supabase started"
fi

# ── 4. Get Supabase credentials ─────────────────────────────────────
ANON_KEY=$(supabase status --output json | jq -r '.PUBLISHABLE_KEY')
SERVICE_ROLE_KEY=$(supabase status --output json | jq -r '.SECRET_KEY')
API_URL=$(supabase status --output json | jq -r '.API_URL')
STUDIO_URL=$(supabase status --output json | jq -r '.STUDIO_URL')

echo ""
echo "  Supabase API:    $API_URL"
echo "  Supabase Studio: $STUDIO_URL"

# ── 5. Configure .env.local for localhost ────────────────────────────
ENV_FILE="$REPO_ROOT/.env.local"

# Backup existing if it has tunnel config
if [[ -f "$ENV_FILE" ]] && grep -q "fuxialexander\.work" "$ENV_FILE" 2>/dev/null; then
  cp "$ENV_FILE" "$ENV_FILE.tunnel-backup"
  echo ""
  echo "  ✓ Backed up tunnel .env.local → .env.local.tunnel-backup"
fi

cat > "$ENV_FILE" << EOF
# Auto-generated by dev-supabase-local.sh
# To restore tunnel config: cp .env.local.tunnel-backup .env.local

# WebAuthn — localhost for local testing
ALLOWED_HOSTS=localhost
WEBAUTHN_RP_NAME=Astro
WEBAUTHN_RP_ID=localhost
WEBAUTHN_ORIGIN=http://localhost:5173

# Local Supabase
SUPABASE_URL=$API_URL
SUPABASE_ANON_KEY=$ANON_KEY
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
VITE_SUPABASE_URL=$API_URL
VITE_SUPABASE_ANON_KEY=$ANON_KEY

# Local dev (no tunnel, no API base URL override)
VITE_API_BASE_URL=
EOF

echo "  ✓ .env.local configured for localhost"

# ── 6. Reset DB if requested ────────────────────────────────────────
if [[ "$RESET_DB" == true ]]; then
  echo ""
  echo "→ Resetting Supabase database..."
  supabase db reset
  echo "  ✓ Database reset with all migrations applied"
fi

# ── 7. Final port check ─────────────────────────────────────────────
echo ""
for PORT in 5173 3001 3002; do
  if lsof -ti :$PORT &>/dev/null; then
    echo "⚠  Port $PORT still in use — force killing..."
    lsof -ti :$PORT | xargs kill -9 2>/dev/null || true
    sleep 0.5
  fi
done

# ── 8. Start dev server ─────────────────────────────────────────────
echo ""
echo "╔══════════════════════════════════════════╗"
echo "║  Starting Astro dev server...            ║"
echo "║                                          ║"
echo "║  Frontend: http://localhost:5173         ║"
echo "║  Backend:  http://localhost:3001         ║"
echo "║  Relay:    ws://localhost:3002           ║"
echo "║  Studio:   $STUDIO_URL    ║"
echo "║                                          ║"
echo "║  Press Ctrl+C to stop                    ║"
echo "╚══════════════════════════════════════════╝"
echo ""

exec npm run dev
