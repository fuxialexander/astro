/**
 * Codegen: generate TypeScript types for the desktop IPC bridge from the
 * Zod channel schemas in electron/main/ipc/schema/*.ts.
 *
 * Strategy: we do NOT evaluate the Zod schemas at codegen time. Instead we
 * statically parse each schema module for its `channels` const and emit a
 * generated .ts file that references the original schemas via type-only
 * imports plus `z.infer<typeof ...>`. This means:
 *   - No extra dependency (no zod-to-ts)
 *   - Types stay in lock-step with the source schemas automatically
 *   - TypeScript itself is the "type engine"
 *
 * Output: src/lib/desktop-bridge.generated.ts
 * Run:    npm run gen:ipc   (tsx scripts/gen-ipc-bridge.ts)
 */

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const ROOT = path.resolve(fileURLToPath(import.meta.url), '../..')
const SCHEMA_DIR = path.join(ROOT, 'electron/main/ipc/schema')
const OUT_FILE = path.join(ROOT, 'src/lib/desktop-bridge.generated.ts')

const MODULES = [
  'fs',
  'git',
  'terminal',
  'watcher',
  'pdf',
  'editor',
  'dialog',
  'windows',
  'server',
  'plugin',
  'layout',
] as const

type ChannelEntry = { channel: string; exportName: string }

/**
 * Parse a schema file and extract its `channels` map:
 *   export const channels = {
 *     'fs:read-file': readFile,
 *     ...
 *   } as const
 */
async function parseChannels(modFile: string): Promise<ChannelEntry[]> {
  const src = await readFile(modFile, 'utf8')
  const match = src.match(/export\s+const\s+channels\s*=\s*\{([\s\S]*?)\}\s*as\s+const/)
  if (!match) {
    throw new Error(`[gen-ipc-bridge] no \`export const channels\` in ${modFile}`)
  }
  const body = match[1]
  const entries: ChannelEntry[] = []
  const lineRe = /['"]([^'"]+)['"]\s*:\s*([A-Za-z_$][\w$]*)/g
  let m: RegExpExecArray | null
  while ((m = lineRe.exec(body)) !== null) {
    entries.push({ channel: m[1], exportName: m[2] })
  }
  if (entries.length === 0) {
    throw new Error(`[gen-ipc-bridge] parsed empty channels in ${modFile}`)
  }
  return entries
}

/** `fs:read-file` → `readFile`; `windows:detach-pane` → `detachPane`. */
function toMethodName(channel: string): string {
  const [, tail] = channel.split(':', 2)
  return tail.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())
}

/** `fs:read-file` → `fs` */
function toNamespace(channel: string): string {
  return channel.split(':', 1)[0]
}

async function main() {
  const perModule: Array<{
    mod: string
    entries: ChannelEntry[]
  }> = []

  for (const mod of MODULES) {
    const file = path.join(SCHEMA_DIR, `${mod}.ts`)
    const entries = await parseChannels(file)
    perModule.push({ mod, entries })
  }

  const lines: string[] = []
  lines.push('/**')
  lines.push(' * AUTO-GENERATED by scripts/gen-ipc-bridge.ts — DO NOT EDIT.')
  lines.push(' *')
  lines.push(' * Run `npm run gen:ipc` to regenerate from')
  lines.push(' * electron/main/ipc/schema/*.ts.')
  lines.push(' */')
  lines.push('')
  // No eslint-disable needed — generated file has no `any` usage.
  lines.push("import type { z } from 'zod'")
  for (const { mod } of perModule) {
    lines.push(
      `import type * as ${mod}Schema from '../../electron/main/ipc/schema/${mod}.ts'`
    )
  }
  lines.push('')

  // IpcChannels: channel → { req, res }
  lines.push('export type IpcChannels = {')
  for (const { mod, entries } of perModule) {
    for (const { channel, exportName } of entries) {
      lines.push(`  '${channel}': {`)
      lines.push(`    req: z.infer<typeof ${mod}Schema.${exportName}.req>`)
      lines.push(`    res: z.infer<typeof ${mod}Schema.${exportName}.res>`)
      lines.push('  }')
    }
  }
  lines.push('}')
  lines.push('')

  // Helpers
  lines.push('export type IpcChannel = keyof IpcChannels')
  lines.push('export type IpcReq<C extends IpcChannel> = IpcChannels[C][\'req\']')
  lines.push('export type IpcRes<C extends IpcChannel> = IpcChannels[C][\'res\']')
  lines.push('')

  // Grouped DesktopBridgeSurface: namespace → { method(req): Promise<res> }
  const namespaces = new Map<string, Array<{ method: string; channel: string }>>()
  for (const { entries } of perModule) {
    for (const { channel } of entries) {
      const ns = toNamespace(channel)
      const method = toMethodName(channel)
      if (!namespaces.has(ns)) namespaces.set(ns, [])
      namespaces.get(ns)!.push({ method, channel })
    }
  }

  lines.push('/**')
  lines.push(' * Shape of the typed bridge grouped by namespace. Each method takes the')
  lines.push(' * channel request payload and returns a promise of the response. The')
  lines.push(' * runtime wrapper in desktop-bridge.ts may layer ergonomic overloads on')
  lines.push(' * top of this — this type just guarantees the payload/return contract.')
  lines.push(' */')
  lines.push('export interface DesktopBridgeSurface {')
  for (const [ns, methods] of namespaces) {
    lines.push(`  ${ns}: {`)
    for (const { method, channel } of methods) {
      lines.push(
        `    ${method}: (req: IpcReq<'${channel}'>) => Promise<IpcRes<'${channel}'>>`
      )
    }
    lines.push('  }')
  }
  lines.push('}')
  lines.push('')

  await writeFile(OUT_FILE, lines.join('\n'), 'utf8')

  let total = 0
  for (const { entries } of perModule) total += entries.length
  console.log(
    `[gen-ipc-bridge] wrote ${path.relative(ROOT, OUT_FILE)} — ${total} channels across ${perModule.length} modules`
  )
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
