/**
 * Build Sidecar Script
 *
 * Bundles the Hono API server (server/index.ts) into a single Node.js file
 * that Tauri can manage as a sidecar process. The bundle includes all server
 * dependencies and the @astro/core package.
 *
 * Output:
 *   src-tauri/sidecar/astro-sidecar.js   — esbuild ESM bundle
 *   src-tauri/sidecar/drizzle/           — PGlite migration files (copied)
 *
 * Usage:
 *   npm run build:sidecar
 *   ASTRO_TAURI=1 node src-tauri/sidecar/astro-sidecar.js
 */

import { build, type BuildOptions } from 'esbuild'
import { cpSync, mkdirSync, existsSync, writeFileSync, readdirSync, statSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const ROOT = join(__dirname, '..')

const SIDECAR_DIR = join(ROOT, 'src-tauri', 'sidecar')
const OUTPUT_FILE = join(SIDECAR_DIR, 'astro-sidecar.js')
const DRIZZLE_SRC = join(ROOT, 'drizzle')
const DRIZZLE_DEST = join(SIDECAR_DIR, 'drizzle')

// Native Node.js modules that cannot be bundled by esbuild.
// These must remain as external imports resolved at runtime.
const NATIVE_EXTERNALS = [
  // Native addons (compiled C++)
  'better-sqlite3',
  // PGlite ships WASM + worker files that esbuild can't inline.
  // It must be resolved from node_modules at runtime.
  '@electric-sql/pglite',
  '@electric-sql/pglite/nodefs',
  // postgres-js uses Node.js net/tls directly — works fine bundled,
  // but we keep it external to avoid issues with its internal file reads.
  'postgres',
  // ioredis has native optional deps
  'ioredis',
]

// Node.js built-in modules — esbuild's `platform: 'node'` handles most,
// but we explicitly list them for the banner polyfill.
const NODE_BUILTINS = [
  'assert', 'buffer', 'child_process', 'cluster', 'console', 'constants',
  'crypto', 'dgram', 'dns', 'domain', 'events', 'fs', 'http', 'http2',
  'https', 'module', 'net', 'os', 'path', 'perf_hooks', 'process',
  'punycode', 'querystring', 'readline', 'repl', 'stream', 'string_decoder',
  'sys', 'timers', 'tls', 'tty', 'url', 'util', 'v8', 'vm', 'wasi',
  'worker_threads', 'zlib',
]

async function main() {
  const startTime = Date.now()
  console.log('[sidecar] Starting build...')

  // 1. Ensure output directories exist
  mkdirSync(SIDECAR_DIR, { recursive: true })

  // 2. Copy drizzle migration files (needed by PGlite at runtime)
  console.log('[sidecar] Copying drizzle migrations...')
  if (existsSync(DRIZZLE_SRC)) {
    cpSync(DRIZZLE_SRC, DRIZZLE_DEST, { recursive: true })
    const sqlFiles = readdirSync(DRIZZLE_DEST).filter(f => f.endsWith('.sql'))
    console.log(`[sidecar] Copied ${sqlFiles.length} migration files`)
  } else {
    console.warn('[sidecar] Warning: drizzle/ directory not found, skipping migrations copy')
    mkdirSync(DRIZZLE_DEST, { recursive: true })
  }

  // 3. Copy skills directory if it exists (loaded at runtime by load-builtin-skills.ts)
  const SKILLS_SRC = join(ROOT, 'skills')
  const SKILLS_DEST = join(SIDECAR_DIR, 'skills')
  if (existsSync(SKILLS_SRC)) {
    console.log('[sidecar] Copying skills directory...')
    cpSync(SKILLS_SRC, SKILLS_DEST, { recursive: true })
  }

  // 4. Copy public/landing if it exists (served by the landing route)
  const LANDING_SRC = join(ROOT, 'public', 'landing')
  const LANDING_DEST = join(SIDECAR_DIR, 'public', 'landing')
  if (existsSync(LANDING_SRC)) {
    console.log('[sidecar] Copying landing page assets...')
    mkdirSync(join(SIDECAR_DIR, 'public'), { recursive: true })
    cpSync(LANDING_SRC, LANDING_DEST, { recursive: true })
  }

  // 5. Build with esbuild
  console.log('[sidecar] Bundling server with esbuild...')

  // Banner that sets ASTRO_TAURI and ASTRO_LOCAL_MODE env vars
  // so the sidecar auto-detects Tauri mode and defaults to local/PGlite.
  // Note: we do NOT define __dirname/__filename here — esbuild's bundled code
  // from server/index.ts already defines them via fileURLToPath(import.meta.url).
  const banner = `
// Astro Sidecar — auto-generated by scripts/build-sidecar.ts
// Set Tauri mode env vars if not already set
if (!process.env.ASTRO_TAURI) process.env.ASTRO_TAURI = '1';
if (!process.env.ASTRO_LOCAL_MODE) process.env.ASTRO_LOCAL_MODE = 'true';

// Default JWT secrets for local/sidecar mode (not used for real auth — local mode skips auth).
// These satisfy the validation in token-manager.ts / environment.ts.
if (!process.env.RELAY_JWT_SECRET) process.env.RELAY_JWT_SECRET = 'astro-sidecar-relay-jwt-secret-local-dev-only-not-for-production';
if (!process.env.DEVICE_AUTH_JWT_SECRET) process.env.DEVICE_AUTH_JWT_SECRET = 'astro-sidecar-device-auth-jwt-secret-local-dev-only-not-for-production';
if (!process.env.DEVICE_AUTH_REFRESH_SECRET) process.env.DEVICE_AUTH_REFRESH_SECRET = 'astro-sidecar-device-refresh-secret-local-dev-only-not-for-production';

// Create a CJS-compatible require() for bundled CJS modules (jsonwebtoken, etc.)
// that call require('buffer'), require('crypto'), etc. In ESM output, the global
// 'require' is undefined, so esbuild's __require shim fails. This fixes it.
import { createRequire as __sidecar_createRequire } from 'module';
const require = __sidecar_createRequire(import.meta.url);
`.trim()

  const buildOptions: BuildOptions = {
    entryPoints: [join(ROOT, 'server', 'index.ts')],
    outfile: OUTPUT_FILE,
    bundle: true,
    platform: 'node',
    target: 'node20',
    format: 'esm',
    sourcemap: true,
    minify: false, // Keep readable for debugging
    treeShaking: true,
    keepNames: true, // Preserve class/function names for error stacks

    // External: native modules + Node.js builtins (both bare and node: prefixed)
    // CJS packages like jsonwebtoken use bare `require('buffer')` while ESM
    // code uses `import 'node:buffer'` — both must be external.
    external: [
      ...NATIVE_EXTERNALS,
      ...NODE_BUILTINS,
      ...NODE_BUILTINS.map(m => `node:${m}`),
    ],

    // Banner: inject env var defaults and ESM __dirname polyfill
    banner: {
      js: banner,
    },

    // Resolve .ts extensions (the codebase uses .js extensions in imports
    // but the actual files are .ts)
    resolveExtensions: ['.ts', '.tsx', '.js', '.jsx', '.json'],

    // Define compile-time constants
    define: {
      'process.env.ASTRO_SIDECAR_BUILD': '"true"',
    },

    // Loader: treat .sql files as text so they can be imported if needed
    loader: {
      '.sql': 'text',
      '.html': 'text',
      '.md': 'text',
    },

    // Alias packages/core imports to resolve correctly
    alias: {
      // The server imports from relative paths like ../../packages/core/src/...
      // These resolve naturally since we're bundling from the repo root.
    },

    // Log level
    logLevel: 'warning',
  }

  try {
    const result = await build(buildOptions)

    if (result.errors.length > 0) {
      console.error('[sidecar] Build errors:')
      for (const error of result.errors) {
        console.error(`  ${error.text}`)
      }
      process.exit(1)
    }

    if (result.warnings.length > 0) {
      console.warn(`[sidecar] Build completed with ${result.warnings.length} warnings`)
    }
  } catch (err) {
    console.error('[sidecar] Build failed:', err)
    process.exit(1)
  }

  // 6. Generate a package.json for the sidecar so `node` can resolve externals
  const sidecarPkg = {
    name: 'astro-sidecar',
    version: '0.0.1',
    type: 'module',
    private: true,
    description: 'Astro sidecar server bundle for Tauri',
    main: 'astro-sidecar.js',
  }
  writeFileSync(
    join(SIDECAR_DIR, 'package.json'),
    JSON.stringify(sidecarPkg, null, 2) + '\n'
  )

  // 7. Print summary
  const elapsed = ((Date.now() - startTime) / 1000).toFixed(1)
  const stats = getFileSize(OUTPUT_FILE)

  console.log('')
  console.log('╔══════════════════════════════════════════════╗')
  console.log('║          Sidecar Build Complete              ║')
  console.log('╠══════════════════════════════════════════════╣')
  console.log(`║  Output:  ${OUTPUT_FILE.replace(ROOT + '/', '')}`)
  console.log(`║  Size:    ${stats}`)
  console.log(`║  Time:    ${elapsed}s`)
  console.log('╠══════════════════════════════════════════════╣')
  console.log('║  To run:                                     ║')
  console.log('║  node src-tauri/sidecar/astro-sidecar.js     ║')
  console.log('╚══════════════════════════════════════════════╝')
  console.log('')
  console.log('[sidecar] External dependencies (must be in node_modules):')
  for (const ext of NATIVE_EXTERNALS) {
    console.log(`  - ${ext}`)
  }
  console.log('')
  console.log('[sidecar] The sidecar defaults to ASTRO_TAURI=1 and ASTRO_LOCAL_MODE=true')
  console.log('[sidecar] It will use PGlite (no auth, single-user) on port 3001.')
}

function getFileSize(filePath: string): string {
  try {
    const stats = statSync(filePath)
    const mb = stats.size / (1024 * 1024)
    return mb >= 1 ? `${mb.toFixed(1)} MB` : `${(stats.size / 1024).toFixed(0)} KB`
  } catch {
    return 'unknown'
  }
}

main().catch((err) => {
  console.error('[sidecar] Fatal error:', err)
  process.exit(1)
})
