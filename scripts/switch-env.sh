#!/usr/bin/env bash
set -euo pipefail

# ─────────────────────────────────────────────────────────────────────
# switch-env.sh — Switch between local, dev, and prod environment profiles
#
# Three modes:
#   local  — PGlite, no auth, no Supabase (removes .env.local)
#   dev    — Local Supabase + Cloudflare tunnel (WebAuthn over HTTPS)
#   prod   — Remote Supabase + Fly.io + Cloudflare Pages
#
# Usage:
#   bash scripts/switch-env.sh local     # PGlite, no auth
#   bash scripts/switch-env.sh dev       # Local Supabase + Cloudflare tunnel
#   bash scripts/switch-env.sh prod      # Fly.io + Cloudflare Pages
#   bash scripts/switch-env.sh status    # Show current mode
#   bash scripts/switch-env.sh init      # Generate dev + prod profiles
#
# How it works:
#   - Saves mode-specific env to .env.local.dev and .env.prod
#   - Symlinks .env.local → the active profile
#   - "local" mode removes .env.local entirely (no Supabase = auto-detected PGlite)
#   - .env holds shared secrets (JWT keys, CLOUDFLARED_DOMAIN) — never touched
#   - Vite + tsx both load .env + .env.local automatically
# ─────────────────────────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

ENV_LOCAL="$REPO_ROOT/.env.local"
ENV_DEV="$REPO_ROOT/.env.local.dev"
ENV_PROD="$REPO_ROOT/.env.prod"

# Load .env for shared vars (CLOUDFLARED_DOMAIN, FLY_APP, etc.)
if [[ -f "$REPO_ROOT/.env" ]]; then
  set -a
  source "$REPO_ROOT/.env"
  set +a
fi

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
CYAN='\033[0;36m'
NC='\033[0m'

# Kill processes on dev ports (5173, 3001, 3002)
kill_ports() {
  local ports=(5173 3001 3002)
  for port in "${ports[@]}"; do
    local pids
    pids=$(lsof -ti ":$port" 2>/dev/null || true)
    if [[ -n "$pids" ]]; then
      echo "  Killing process on port $port (PID: $pids)"
      echo "$pids" | xargs kill -9 2>/dev/null || true
    fi
  done
}

show_status() {
  if [[ -L "$ENV_LOCAL" ]]; then
    local target
    target=$(readlink "$ENV_LOCAL")
    if [[ "$target" == *".local.dev" ]]; then
      echo -e "${GREEN}Current mode: dev${NC} (.env.local → .env.local.dev)"
    elif [[ "$target" == *".prod" ]]; then
      echo -e "${CYAN}Current mode: prod${NC} (.env.local → .env.prod)"
    else
      echo -e "${YELLOW}Current mode: custom${NC} (.env.local → $target)"
    fi
  elif [[ -f "$ENV_LOCAL" ]]; then
    echo -e "${YELLOW}Current mode: unknown${NC} (.env.local is a regular file, not managed by switch-env)"
    echo "  Run 'bash scripts/switch-env.sh init' to set up profiles"
  else
    echo -e "${GREEN}Current mode: local${NC} (no .env.local — PGlite, no auth)"
  fi
}

init_profiles() {
  echo "Initializing env profiles..."
  echo ""

  # ── Dev profile (local Supabase + Cloudflare tunnel) ──
  if [[ -f "$ENV_DEV" ]]; then
    echo -e "${YELLOW}  .env.local.dev already exists — skipping${NC}"
  else
    # Require CLOUDFLARED_DOMAIN for tunnel-based WebAuthn
    local domain="${CLOUDFLARED_DOMAIN:-}"
    if [[ -z "$domain" ]]; then
      echo -e "${RED}  CLOUDFLARED_DOMAIN not set in .env${NC}"
      echo "  Add CLOUDFLARED_DOMAIN=your-domain.com to .env and re-run init"
      echo "  (This is the domain your Cloudflare tunnel uses)"
      echo ""
    else
      local app_subdomain="astro.$domain"
      local supabase_subdomain="astro-supabase.$domain"

      # Try to get Supabase creds if running
      local anon_key=""
      local service_key=""

      if command -v supabase &>/dev/null && supabase status &>/dev/null 2>&1; then
        anon_key=$(supabase status --output json | jq -r '.PUBLISHABLE_KEY' 2>/dev/null || true)
        service_key=$(supabase status --output json | jq -r '.SECRET_KEY' 2>/dev/null || true)
        echo "  Detected running Supabase"
      fi

      cat > "$ENV_DEV" << EOF
# Astro — Dev (local Supabase + Cloudflare tunnel)
# Generated by: bash scripts/switch-env.sh init
# Tunnel domain: $domain

# WebAuthn — tunnel domain for HTTPS (required for TouchID/passkeys)
WEBAUTHN_RP_NAME=Astro
WEBAUTHN_RP_ID=$app_subdomain
WEBAUTHN_ORIGIN=https://$app_subdomain
ALLOWED_HOSTS=$app_subdomain,$domain,localhost

# Local Supabase exposed via tunnel
SUPABASE_URL=https://$supabase_subdomain
SUPABASE_ANON_KEY=$anon_key
SUPABASE_SERVICE_ROLE_KEY=$service_key
VITE_SUPABASE_URL=https://$supabase_subdomain
VITE_SUPABASE_ANON_KEY=$anon_key

# HMR over tunnel
VITE_HMR_PROTOCOL=wss
VITE_HMR_HOST=$app_subdomain
VITE_HMR_PORT=443

# No API base URL override (tunnel proxies everything)
VITE_API_BASE_URL=
EOF
      chmod 600 "$ENV_DEV"
      echo -e "${GREEN}  Created .env.local.dev${NC}"
    fi
  fi

  # ── Prod profile (Fly.io + Cloudflare Pages + remote Supabase) ──
  if [[ -f "$ENV_PROD" ]]; then
    echo -e "${YELLOW}  .env.prod already exists — skipping${NC}"
  else
    local fly_app="${FLY_APP:-astro-backend-platform}"
    local pages_project="${CLOUDFLARE_PAGES_PROJECT:-astro-app}"
    local branch
    branch=$(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo "main")

    local frontend_url
    if [[ "$branch" == "main" ]]; then
      frontend_url="https://${pages_project}.pages.dev"
    else
      local sanitized
      sanitized=$(echo "$branch" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9]/-/g' | sed 's/--*/-/g' | sed 's/^-//;s/-$//')
      frontend_url="https://${sanitized}.${pages_project}.pages.dev"
    fi

    local backend_url="https://${fly_app}.fly.dev"
    local pages_domain
    pages_domain=$(echo "$frontend_url" | sed 's|https\?://||' | sed 's|/.*||')

    cat > "$ENV_PROD" << EOF
# Astro — Prod (Fly.io + Cloudflare Pages)
# Generated by: bash scripts/switch-env.sh init
# Branch: $branch

# WebAuthn — must match Cloudflare Pages frontend domain
WEBAUTHN_RP_NAME=Astro
WEBAUTHN_RP_ID=$pages_domain
WEBAUTHN_ORIGIN=$frontend_url
ALLOWED_HOSTS=$pages_domain,localhost

# CORS / frontend URL
CORS_ORIGIN=$frontend_url
FRONTEND_URL=$frontend_url
ASTRO_BASE_URL=$frontend_url

# Frontend build — point API calls to Fly.io backend (bypasses Cloudflare for SSE)
VITE_API_BASE_URL=$backend_url

# Remote Supabase — fill in your production credentials
# SUPABASE_URL=https://XXXX.supabase.co
# SUPABASE_ANON_KEY=eyJ...
# SUPABASE_SERVICE_ROLE_KEY=eyJ...
# VITE_SUPABASE_URL=https://XXXX.supabase.co
# VITE_SUPABASE_ANON_KEY=eyJ...
EOF
    chmod 600 "$ENV_PROD"
    echo -e "${GREEN}  Created .env.prod${NC}"
    echo -e "  ${YELLOW}Edit .env.prod to fill in remote Supabase credentials${NC}"
  fi

  echo ""

  # Default to local if no .env.local exists
  if [[ ! -e "$ENV_LOCAL" ]]; then
    echo -e "${GREEN}  Default mode: local${NC} (no .env.local needed)"
    echo "  Switch with: npm run env:dev or npm run env:prod"
  else
    show_status
  fi
}

switch_to() {
  local mode="$1"

  # Kill stale processes on dev ports
  echo "Cleaning up ports..."
  kill_ports

  case "$mode" in
    local)
      # Remove .env.local so no Supabase config is loaded
      # Server auto-detects PGlite when SUPABASE_URL is absent
      rm -f "$ENV_LOCAL"
      echo -e "${GREEN}Switched to local mode${NC} (PGlite, no auth)"
      echo ""
      echo "Next steps:"
      echo "  npm run dev              # Start dev server"
      return
      ;;
    dev)
      if [[ ! -f "$ENV_DEV" ]]; then
        echo -e "${RED}Profile not found: $ENV_DEV${NC}"
        echo "Run 'bash scripts/switch-env.sh init' first"
        exit 1
      fi
      rm -f "$ENV_LOCAL"
      ln -s "$(basename "$ENV_DEV")" "$ENV_LOCAL"
      echo -e "${GREEN}Switched to dev mode${NC}"
      show_status
      echo ""
      echo "Next steps:"
      echo "  npm run tunnel           # Start Cloudflare tunnel"
      echo "  npm run dev              # Start dev server (in another terminal)"
      ;;
    prod)
      if [[ ! -f "$ENV_PROD" ]]; then
        echo -e "${RED}Profile not found: $ENV_PROD${NC}"
        echo "Run 'bash scripts/switch-env.sh init' first"
        exit 1
      fi
      rm -f "$ENV_LOCAL"
      ln -s "$(basename "$ENV_PROD")" "$ENV_LOCAL"
      echo -e "${GREEN}Switched to prod mode${NC}"
      show_status
      echo ""
      echo "Next steps:"
      echo "  npm run build            # Build frontend with VITE_API_BASE_URL baked in"
      echo "  npm run deploy           # Deploy backend + frontend"
      ;;
    *)
      echo -e "${RED}Unknown mode: $mode${NC}"
      echo "Usage: bash scripts/switch-env.sh [local|dev|prod|status|init]"
      exit 1
      ;;
  esac
}

# ── Main ──────────────────────────────────────────────────────────────
case "${1:-status}" in
  local|dev|prod) switch_to "$1" ;;
  status)         show_status ;;
  init)           init_profiles ;;
  *)
    echo "Usage: bash scripts/switch-env.sh [local|dev|prod|status|init]"
    echo ""
    echo "Modes:"
    echo "  local    PGlite, no auth, all localhost"
    echo "  dev      Local Supabase + Cloudflare tunnel"
    echo "  prod     Fly.io + Cloudflare Pages + remote Supabase"
    echo ""
    echo "Commands:"
    echo "  local    Switch to local mode (removes .env.local)"
    echo "  dev      Switch to dev mode"
    echo "  prod     Switch to prod mode"
    echo "  status   Show current mode (default)"
    echo "  init     Generate .env.local.dev and .env.prod profiles"
    exit 1
    ;;
esac
